/**
 * Fail-closed activation policy. The replacement mutation is unavailable
 * until a separately configured HOMOLOGATION instance has the audited RPC.
 *
 * Never infer readiness just because a UI or public function exists.
 */
export function canRunSalesReplacementInStaging(
  enabled: string | undefined,
  environment: string | undefined,
): boolean {
  return enabled === "true" && environment === "homologation";
}

export function assertSalesReplacementInStaging(
  enabled: string | undefined,
  environment: string | undefined,
): void {
  if (!canRunSalesReplacementInStaging(enabled, environment)) {
    throw new Error(
      "Substituição transacional desativada. Só é permitida em homologação com RPC auditada.",
    );
  }
}

/**
 * The database version is an MD5 of ALL sales rows of the month
 * (including soft-deleted records), generated by public.sales_month_version.
 * This is a concurrency fingerprint, NOT a secret or authentication token.
 */
export function isSalesMonthDatabaseVersion(version: unknown): version is string {
  return typeof version === "string" && /^[a-f0-9]{32}$/.test(version);
}
